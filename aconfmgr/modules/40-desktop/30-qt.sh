# Qt 5 Wayland platform plugin and client libraries. They let Qt 5 applications
# use Wayland natively instead of running through Xwayland.
AddPackage qt5-wayland

# Qt 6 Wayland platform plugin and client libraries. They let Qt 6 applications
# use Wayland natively instead of running through Xwayland.
AddPackage qt6-wayland

# qt5ct exposes Qt 5 appearance, font, icon, and behavior preferences outside
# a full Qt desktop environment.
AddPackage qt5ct

# qt6ct exposes the equivalent appearance, font, icon, and behavior preferences
# for Qt 6 applications.
AddPackage qt6ct

# Kvantum is an SVG-based theming engine and configuration utility for Qt 6.
AddPackage kvantum

# Qt 5 platform theme plugin for Kvantum, allowing the same theme engine to be
# used by Qt 5 applications.
AddPackage kvantum-qt5

# Adwaita-style Qt 5 widget theme for applications that should visually align
# with GTK/Adwaita applications.
AddPackage adwaita-qt5

# Adwaita-style Qt 6 widget theme for applications that should visually align
# with GTK/Adwaita applications.
AddPackage adwaita-qt6

# Qt 6 development and diagnostic utilities, including Qt Help tools.
AddPackage qt6-tools
